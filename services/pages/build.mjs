// Bundles the page service into dist/server.mjs (docs/pages.md, "Page
// service"). The bundle holds the service, the shared page rules engine
// (src/shared/pages), the node:sqlite adapter, and the sandbox intermediary,
// so the deployed service has no npm dependencies. Run from the repository
// root with `npm run pages:build`; esbuild comes from the root install.
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));

await build({
  entryPoints: [join(here, "src", "main.ts")],
  outfile: join(here, "dist", "server.mjs"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  packages: "bundle",
  legalComments: "none",
  logLevel: "info",
  banner: { js: "// work-fold page service. Generated by services/pages/build.mjs; do not edit." },
});
