/**
 * File and folder icons for Files, attachments, and file details.
 *
 * Every glyph comes from vscode-icons (MIT), drawn in its own colors; several
 * types also carry a light-theme variant. A few vscode-icons drawings are too
 * heavy for a Files row (the generator caps each glyph at 12 KB), so those
 * types use their language's or family's icon instead (Cargo → Rust,
 * Composer → PHP, LICENSE → text). Glyph ids are `vs:<name>`. A type
 * vscode-icons does not draw gets its closest general icon (text, image,
 * archive, config, and so on).
 *
 * The SVG data is vendored in `file-icons-data.ts`, which
 * `scripts/generate-file-icons.mjs` regenerates from the ids used below. After
 * adding or changing a glyph id here, rerun that script.
 *
 * work-folders are deliberately plain: every folder gets the same closed and open
 * glyph, whatever its name, so no folder looks special.
 */
import { fileIconGlyphs, type FileIconGlyph } from "./file-icons-data";

export { fileIconArtworkMarkup } from "./file-icons-data";

export interface FileTreeIconSpec {
  /** Vendored glyph id, for example `vs:file-type-docker`. */
  glyph: string;
  label: string;
}

function icon(glyph: string, label: string): FileTreeIconSpec {
  return { glyph, label };
}

