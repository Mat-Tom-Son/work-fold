const fileNameIconMap = new Map<string, FileTreeIconSpec>();
for (const [kind, names] of fileNameGroups) {
  for (const name of names.split(/\s+/)) fileNameIconMap.set(name, kinds[kind]);
}

const extensionIconMap = new Map<string, FileTreeIconSpec>();
let longestExtensionParts = 1;
for (const [kind, extensions] of extensionGroups) {
  for (const extension of extensions.split(/\s+/)) {
    extensionIconMap.set(extension, kinds[kind]);
    longestExtensionParts = Math.max(longestExtensionParts, extension.split(".").length);
  }
}

export function fileTreeFileIcon(path: string): FileTreeIconSpec {
  const normalizedPath = path.replace(/\\/g, "/").toLowerCase();
  const name = baseName(normalizedPath);
  const exact = fileNameIconMap.get(name);
  if (exact) return exact;
  for (const [pattern, kind] of pathPatterns) if (pattern.test(normalizedPath)) return kinds[kind];
  for (const [pattern, kind] of fileNamePatterns) if (pattern.test(name)) return kinds[kind];
  for (const [pattern, kind] of nameRules) if (pattern.test(name)) return kinds[kind];
  return extensionIcon(name) ?? fallbackFileIcon;
}

/** Every folder gets the same plain glyph; the name never changes it. */
export function fileTreeFolderIcon(_pathOrName: string, expanded: boolean): FileTreeIconSpec {
  return expanded ? openFolderIcon : closedFolderIcon;
}

export function fileTreeIconGlyph(iconSpec: FileTreeIconSpec): FileIconGlyph {
  return fileIconGlyphs[iconSpec.glyph] ?? fileIconGlyphs[fallbackFileIcon.glyph]!;
}

/** All icon specs the resolver can return (for tests and the generator). */
export function allFileTreeIconSpecs(): FileTreeIconSpec[] {
  return [fallbackFileIcon, closedFolderIcon, openFolderIcon, ...Object.values(kinds)];
}

function extensionIcon(name: string): FileTreeIconSpec | undefined {
  // A leading dot marks a hidden file, not an extension: `.bashrc` has the
  // extension `bashrc`, while `notes` has none.
  const parts = name.replace(/^\.+/, "").split(".");
  if (parts.length < 2 && !name.startsWith(".")) return undefined;
  const firstExtensionIndex = name.startsWith(".") && parts.length === 1 ? 0 : 1;
  const longest = Math.min(longestExtensionParts, parts.length - firstExtensionIndex);
  for (let count = longest; count >= 1; count -= 1) {
    const match = extensionIconMap.get(parts.slice(parts.length - count).join("."));
    if (match) return match;
  }
  return undefined;
}

function baseName(path: string): string {
  return path.split("/").filter(Boolean).pop() ?? path;
}
